"""Спецификации соцобъектов для расчёта v0.1."""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

KGType = Literal["detached", "built_in"]


class KindergartenSpec(BaseModel):
    """Структура ДОО на участке. По умолчанию — все мест распределяем по
    отдельностоящим ДОО с автоматическим количеством объектов."""
    model_config = ConfigDict(extra="forbid")

    building_type: KGType = "detached"
    # если задано — фиксированное число объектов и вместимость каждого
    num_objects: int | None = None
    capacity_per_object: int | None = None
    # «Только потребность»: ЗУ и здание ДОО не учитываются в балансе квартала
    # и не вычитаются из жилой GFA (для built_in). Используется когда ДОО
    # размещается за пределами квартала или уже существует. Места требуемые/
    # принятые при этом считаются и показываются как обычно.
    only_demand: bool = Field(
        default=False,
        description="ДОО учитывается только для расчёта потребности; ЗУ/здание не входят в баланс",
    )
    # v0.12.4: «только нормативная наполняемость» — вместимости корпусов ДОО
    # берутся ТОЛЬКО из типового списка (СП / письмо КОБр), а не произвольным
    # кратным. По умолчанию выкл (свободная разбивка).
    strict_capacity: bool = Field(
        default=False,
        description="Вместимости ДОО только из нормативного списка (СП/КОБр)",
    )


class SchoolSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    building_type: Literal["detached"] = "detached"
    # По умолчанию — стандартная СОШ СПб с бассейном (+0.2 га к участку) и
    # спортивным ядром (+0.7 га). Это типовое благоустройство в современных
    # проектах СПб. Если у проекта другая комплектация — отключите явно.
    has_pool: bool = True
    has_sport_core: bool = True
    num_objects: int | None = None
    capacity_per_object: int | None = None
    # «Только потребность»: ЗУ СОШ не учитывается в балансе квартала.
    # Используется когда СОШ размещается за пределами квартала.
    only_demand: bool = Field(
        default=False,
        description="СОШ учитывается только для расчёта потребности; ЗУ не входит в баланс",
    )
    # v0.12.4: «только нормативная наполняемость» — вместимости корпусов СОШ
    # строго из типового списка (СП/КОБр: 550/825/…/2475).
    strict_capacity: bool = Field(
        default=False,
        description="Вместимости СОШ только из нормативного списка (СП/КОБр)",
    )


class AdditionalEducationSpec(BaseModel):
    """Организации дополнительного образования детей (ВРИ 3.5.1), v0.12.15.

    Норматив (РМД 15-26-2017 + НГП СПб): 65 мест/1000 чел, работники = места/6,
    здание 17 м²/место. Размещение по порогу 150 мест:
      < 150 → встроенно-пристроенное (ВПП): здание вычитается из жилой GFA;
      ≥ 150 → отдельно стоящее: ЗУ 15 м²/место + 30% озеленения.

    Режимы:
      mode="norm"   — места и размещение по нормативу (порог 150 мест);
      mode="manual" — пользователь задаёт число мест и сам выбирает `in_vpp`.
    """
    model_config = ConfigDict(extra="forbid")

    mode: Literal["norm", "manual"] = "norm"
    # Ручной режим: число мест и принудительное размещение в ВПП.
    places_override: int | None = Field(default=None, ge=0)
    in_vpp: bool = Field(
        default=False,
        description="Ручной режим: разместить во встроенно-пристроенном (ВПП)",
    )
    # «Только потребность»: объект учитывается для подсчёта мест, но ЗУ/здание
    # не входят в баланс квартала и не вычитают жилую GFA.
    only_demand: bool = Field(
        default=False,
        description="Доп. образование только для расчёта потребности; ЗУ/здание не в балансе",
    )


class SportFacilitiesSpec(BaseModel):
    """Плоскостные спортивные сооружения (ВРИ 5.1.3, v0.6.8).

    Норматив: 1000 м²/1000 чел + озеленение 40% от ЗУ.
    При этом до 49% озеленения может быть замещено самой спортплощадкой
    (п. 1.9.4 ПЗЗ СПб): на ЗУ нужно ДОПОЛНИТЕЛЬНО (1−0.49)×40% = 20.4% озеленения.
    """
    model_config = ConfigDict(extra="forbid")

    only_demand: bool = Field(
        default=False,
        description="Спортплощадки учитываются только для расчёта потребности; ЗУ не входит в баланс",
    )
    # Если задано — заменяет нормативное значение (население × area_per_1000 / 1000).
    # Использует пользователь, когда у него есть конкретная площадь спортплощадок
    # (например, существующее сооружение или индивидуальный проект).
    area_override_m2: float | None = Field(
        default=None,
        ge=0.0,
        description="Принудительная площадь самих спортплощадок, м². None = норматив.",
    )
