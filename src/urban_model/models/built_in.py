"""ВПП — встроенно-пристроенные помещения как самостоятельная сущность (v0.2).

В v0.1 ВПП учитывались только как доля в GFA (`vpp_share`) — без собственных
парковок и озеленения. Здесь — полноценная сущность с одним ВРИ:
  - площадь ВПП вычитается из GFA при расчёте площади квартир,
  - парковки ВПП считаются по нормативу parking.vpp.m2_per_place(vri_code),
  - озеленение ВПП — по greening.vpp_per_floor_area (15 м²/100 м²),
  - ВПП пятна не имеет (встроены в жильё или пристроены к нему),
    поэтому в баланс отдельным компонентом не входит.

Список встроенных помещений с разными ВРИ — следующий шаг (B3),
сейчас одно ВПП = один ВРИ-код.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

# Поддерживаемые ВРИ-коды для ВПП (соответствуют parking.vpp.m2_per_place в spb.yaml).
# При расширении достаточно добавить ВРИ в YAML — Literal не блокирует resolve.
VPP_VRI = Literal[
    "2.6",   # жильё
    "3.3",   # бытовое обслуживание
    "3.6",   # культурное развитие
    "3.7",   # религиозное использование
    "4.0",   # общее предпринимательство
    "4.1",   # деловое управление
    "4.4",   # магазины
    "4.5",   # банки, страховые
    "4.6",   # общественное питание
]


class BuiltInArea(BaseModel):
    """Встроенно-пристроенное помещение в составе жилого здания.

    Площадь ВПП вычитается из общей площади (GFA) при расчёте квартир,
    но добавляет нагрузку на парковки и озеленение по своему ВРИ.
    """

    model_config = ConfigDict(extra="forbid")

    area_m2: float = Field(
        gt=0.0,
        description="Площадь ВПП в составе GFA, м²",
    )
    vri_code: str = Field(
        default="4.4",
        description=(
            "Вид разрешённого использования ВПП (по Приказу №П-0412). "
            "По умолчанию 4.4 — магазины. См. dict/dict_vri.yaml."
        ),
    )
    label: str | None = Field(
        default=None,
        description="Произвольная подпись для отчётов (например, 'торговый центр')",
    )

    def __str__(self) -> str:
        lbl = f" ({self.label})" if self.label else ""
        return f"ВПП {self.area_m2:,.0f} м², ВРИ {self.vri_code}{lbl}"
